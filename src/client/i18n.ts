export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem("basket-lang");
    if (saved === "ja" || saved === "en") return saved;
  } catch {
    /* ignore */
  }
  if (typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("ja")) return "ja";
  return "en";
}

export function t(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  let s = dict[lang][key] || dict.en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function tError(lang: Lang, message: string): string {
  const key = errorMap[message];
  return key ? t(lang, key) : message;
}

